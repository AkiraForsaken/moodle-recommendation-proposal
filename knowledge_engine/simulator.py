"""Simulated learners in the Moodle collector's own file format.

WHY THIS EXISTS
    A real course starts with no answers and may never reach the volume a deep
    KT model needs. The simulator lets Phase 2 (training) and Phase 3
    (promotion gate, personalised estimates) be exercised end to end.

WHAT IT PROVES (and does not)
    Results on simulated learners show that the pipeline and the gate work.
    They are properties of this generator, NOT evidence that any estimate is
    valid for real learners. Every output directory carries a
    ``simulation_manifest.json``; the engine and the learner model label such
    data ``simulated`` and never ``moodle_collector``.

THE GENERATOR IS DELIBERATELY NOT BKT
    Answers come from an item-response model with continuous ability, item and
    KC difficulty, practice gains with diminishing returns, and forgetting over
    elapsed time. If answers were generated by BKT, the Phase 1 BKT estimator
    would be the true model and the promotion gate would be rigged in its
    favour.

The course (KCs, questions, topics) is taken from a collector export when one
is given; otherwise a small synthetic course is generated.
"""

import shutil
from pathlib import Path

import numpy as np
import pandas as pd

from collector.collect_question_answers import ANSWER_EVENT_COLUMNS, ROSTER_COLUMNS

from .config import DEFAULT_SIMULATED_DIR, SIMULATION_MANIFEST_NAME
from .data import (
    ANSWER_EVENTS_FILE,
    KC_CATALOG_FILE,
    QUESTION_KC_MAP_FILE,
    ROSTER_FILE,
    write_json,
)

KC_TOPIC_MAP_FILE = "kc_topic_map.csv"
DEFAULT_START_UNIX = 1_780_000_000  # fixed so runs are reproducible
DAY = 86_400
GUESS_FLOOR = 0.20
SIMULATED_COURSE_ID = 0
# Share of a lesson's effect relative to one practice answer (generator assumption).
DEFAULT_LESSON_GAIN = 0.5
DEFAULT_PASS_FRACTION = 0.7


def make_course(
    n_topics=6,
    dimensions=("grammar", "vocabulary", "reading", "writing"),
    questions_per_kc=10,
):
    """A synthetic course: one KC per topic and dimension."""
    catalog, question_map, topic_map = [], [], []
    version = f"sim-course-{n_topics}x{len(dimensions)}x{questions_per_kc}"
    entry_id = 0
    for topic_index in range(1, n_topics + 1):
        topic = f"Unit {topic_index}"
        for dimension in dimensions:
            kc_id = f"SIM-KC{len(catalog) + 1:03d}"
            catalog.append(
                {
                    "kc_id": kc_id,
                    "kc_name": f"{topic} {dimension}",
                    "kc_dimension": dimension,
                    "learning_objective": f"Simulated {dimension} objective for {topic}.",
                }
            )
            topic_map.append(
                {"kc_id": kc_id, "topic": topic, "mapping_version": version}
            )
            for _ in range(questions_per_kc):
                entry_id += 1
                question_map.append(
                    {
                        "question_bank_entry_id": str(entry_id),
                        "kc_id": kc_id,
                        "kc_dimension": dimension,
                        "mapping_version": version,
                        "mapping_source": "simulator",
                    }
                )
    return pd.DataFrame(catalog), pd.DataFrame(question_map), pd.DataFrame(topic_map)


def load_course(course_dir):
    """Reuse the KCs, questions and topics of a collector export."""
    course_dir = Path(course_dir)
    catalog = pd.read_csv(course_dir / KC_CATALOG_FILE, dtype="string")
    question_map = pd.read_csv(course_dir / QUESTION_KC_MAP_FILE, dtype="string")
    topic_file = course_dir / KC_TOPIC_MAP_FILE
    topic_map = (
        pd.read_csv(topic_file, dtype="string")
        if topic_file.is_file()
        else pd.DataFrame(columns=["kc_id", "topic", "mapping_version"])
    )
    if catalog.empty or question_map.empty:
        raise ValueError(f"{course_dir} has no KCs or no mapped questions to simulate")
    return catalog, question_map, topic_map


def _topic_groups(catalog, question_map, topic_map):
    """Ordered list of (topic, [kc_id]) covering every KC that has questions."""
    usable = set(question_map["kc_id"])
    groups = {}
    for kc_id, topic in topic_map[["kc_id", "topic"]].itertuples(index=False):
        if kc_id in usable:
            groups.setdefault(str(topic), []).append(str(kc_id))
    placed = {kc for kcs in groups.values() for kc in kcs}
    for kc_id, dimension in catalog[["kc_id", "kc_dimension"]].itertuples(index=False):
        if kc_id in usable and kc_id not in placed:
            groups.setdefault(f"Unmapped topic: {dimension}", []).append(str(kc_id))
    return list(groups.items())


def ceiling_auc(probabilities, outcomes):
    """AUC of the generator's own answer probabilities against the outcomes.

    No estimator can be expected to beat this on the simulated data: it is what
    a model that knew every hidden learner and item parameter would score.
    """
    frame = pd.DataFrame({"p": probabilities, "y": outcomes})
    positives = int(frame["y"].sum())
    negatives = len(frame) - positives
    if positives == 0 or negatives == 0:
        return None
    ranks = frame["p"].rank(method="average")
    u_statistic = ranks[frame["y"].eq(1)].sum() - positives * (positives + 1) / 2
    return round(float(u_statistic / (positives * negatives)), 4)


def _pass_fraction(quiz, default):
    """Share of the marks a quiz needs to count as passed."""
    grade, gradepass = quiz.get("grade"), quiz.get("gradepass")
    if grade and gradepass:
        return float(gradepass) / float(grade)
    return default


def simulate_plan(
    quizzes,
    n_learners=300,
    seed=7,
    start_unix=DEFAULT_START_UNIX,
    inactive_share=0.05,
    session_scale=3.5,
    sample_range=None,
    lessons=None,
    overviews=None,
    lesson_gain=DEFAULT_LESSON_GAIN,
    pass_fraction=DEFAULT_PASS_FRACTION,
):
    """Decide every simulated learner's quiz attempts, answers and page views.

    ``quizzes`` is the course's ordered quiz list, each
    ``{"quiz_id": ..., "entries": [{"entry_id": ..., "kc_id": ...}, ...]}``,
    optionally with ``cmid``, ``section``, ``grade`` and ``gradepass``. One
    session is one attempt on one quiz. By default the attempt answers every
    question of the quiz in order; with ``sample_range=(low, high)`` it answers
    a random subset of that size instead.

    A learner enters the course at a random quiz, then works forward in course
    order (wrapping around), moving on after passing a quiz and sometimes going
    back to review an earlier one. The mean number of sessions is about
    ``1 + 2 * session_scale``.

    With ``lessons`` (kc_id -> page cmid) the learner also uses the course's
    learning pages, as in Moodle:

    * views the unit overview (``overviews``: section -> cmid) before the
      first attempt in a unit;
    * with probability ``study_propensity`` (a learner trait) reads the
      lessons of some of a quiz's KCs before the first attempt on it;
    * after failing a quiz, with probability ``revise_propensity`` makes the
      next session a revision: reads the lessons of the KCs answered below the
      pass mark in that attempt, then retries the same quiz;
    * sometimes reviews a finished attempt shortly afterwards.

    Reading a lesson adds ``lesson_gain * learn_rate`` to the KC's practice
    gain (set ``lesson_gain=0`` for no effect). That a lesson helps at all is
    an ASSUMPTION of this generator, not a finding. Without ``lessons`` no
    page behaviour is generated and no extra random numbers are drawn, so
    offline simulation is unchanged.

    Returns ``(plan, manifest)``. ``plan`` is a list with one entry per learner:
    ``{"number", "learner_id", "enrol_start", "attempts": [{"quiz_id",
    "attempt_number", "start", "finish", "revision", "views_before": [{"cmid",
    "kind", "kc_id", "time"}], "review_at", "answers": [{"entry_id", "kc_id",
    "correct", "partial", "time", "seconds"}]}]}``. The first ``k`` learners
    of a plan are identical whatever the cohort size, so a cohort can be
    extended.
    """
    quizzes = [quiz for quiz in quizzes if quiz["entries"]]
    if not quizzes:
        raise ValueError("The course has no quiz with KC-mapped questions to simulate")
    use_pages = bool(lessons)
    lessons = {str(kc): int(cmid) for kc, cmid in (lessons or {}).items()}
    overviews = {str(section): int(cmid) for section, cmid in (overviews or {}).items()}
    rng = np.random.default_rng(seed)
    kc_ids = sorted({str(e["kc_id"]) for quiz in quizzes for e in quiz["entries"]})
    entry_ids = sorted(
        {str(e["entry_id"]) for quiz in quizzes for e in quiz["entries"]}
    )
    kc_difficulty = dict(zip(kc_ids, rng.normal(0.0, 0.7, len(kc_ids))))
    item_difficulty = dict(zip(entry_ids, rng.normal(0.0, 0.5, len(entry_ids))))
    counts = dict.fromkeys(
        ("lesson_views", "overview_views", "revisions", "reviews"), 0
    )

    plan, probabilities, outcomes = [], [], []
    for number in range(1, n_learners + 1):
        enrol = int(start_unix + rng.integers(0, 14 * DAY))
        ability = rng.normal(0.0, 1.0)
        learn_rate = rng.lognormal(np.log(0.35), 0.4)
        half_life_days = rng.lognormal(np.log(30.0), 0.5)
        kc_offset = dict(zip(kc_ids, rng.normal(0.0, 0.5, len(kc_ids))))
        # Always drawn, so one learner's inactivity never shifts another's stream.
        n_sessions = 1 + rng.poisson(rng.gamma(2.0, session_scale))
        entry_point = int(rng.integers(0, len(quizzes)))
        if use_pages:
            study_propensity = rng.beta(2.0, 3.0)
            revise_propensity = rng.beta(2.0, 2.0)
            review_propensity = rng.beta(1.5, 4.0)
        learner = {
            "number": number,
            "learner_id": f"sim-{number:04d}",
            "enrol_start": enrol,
            "attempts": [],
        }
        plan.append(learner)
        if rng.random() < inactive_share:
            continue  # enrolled but never answered: a real cold-start learner

        gain = dict.fromkeys(kc_ids, 0.0)
        practice = dict.fromkeys(kc_ids, 0)
        last_seen, attempts_per_quiz = {}, {}
        seen_sections, revision = set(), None
        progress, clock = 0, enrol  # progress = quizzes passed since the entry point

        def decay(kc_id, now):
            """Forget part of the KC's gain since the learner last worked on it."""
            if kc_id in last_seen:
                elapsed_days = (now - last_seen[kc_id]) / DAY
                gain[kc_id] *= 0.5 ** (elapsed_days / half_life_days)
            last_seen[kc_id] = now

        def view(cmid, kind, kc_id=None):
            """One page view at the current clock; returns its plan entry."""
            nonlocal clock
            entry = {"cmid": cmid, "kind": kind, "kc_id": kc_id, "time": clock}
            seconds = (
                40
                if kind == "overview"
                else int(np.clip(rng.lognormal(np.log(150.0), 0.5), 20, 900))
            )
            clock += seconds
            if kc_id is not None:
                decay(kc_id, clock)
                gain[kc_id] += lesson_gain * learn_rate
                counts["lesson_views"] += 1
            else:
                counts["overview_views"] += 1
            return entry

        for _ in range(n_sessions):
            clock += int(rng.exponential(2.0 * DAY)) + 600
            views = []
            if revision is not None:
                step, weak_kcs = revision
                revision = None
                is_revision = True
                counts["revisions"] += 1
                views += [
                    view(lessons[kc], "lesson", kc) for kc in weak_kcs if kc in lessons
                ]
            else:
                is_revision = False
                review = progress > 0 and rng.random() < 0.3
                step = int(rng.integers(0, progress)) if review else progress
            quiz = quizzes[(entry_point + step) % len(quizzes)]
            quiz_key = quiz["quiz_id"]
            quiz_kcs = list(dict.fromkeys(str(e["kc_id"]) for e in quiz["entries"]))
            if use_pages:
                section = str(quiz.get("section"))
                if section not in seen_sections and section in overviews:
                    views.append(view(overviews[section], "overview"))
                seen_sections.add(section)
                if (
                    quiz_key not in attempts_per_quiz
                    and rng.random() < study_propensity
                ):
                    size = int(rng.integers(1, len(quiz_kcs) + 1))
                    chosen = set(
                        rng.choice(len(quiz_kcs), size=size, replace=False).tolist()
                    )
                    views += [
                        view(lessons[kc], "lesson", kc)
                        for index, kc in enumerate(quiz_kcs)
                        if index in chosen and kc in lessons
                    ]
            entries = quiz["entries"]
            if sample_range is not None:
                size = min(
                    len(entries),
                    int(rng.integers(sample_range[0], sample_range[1] + 1)),
                )
                entries = [
                    entries[i]
                    for i in rng.choice(len(entries), size=size, replace=False)
                ]
            attempts_per_quiz[quiz_key] = attempts_per_quiz.get(quiz_key, 0) + 1
            if views:
                clock += 30
            attempt = {
                "quiz_id": quiz_key,
                "attempt_number": attempts_per_quiz[quiz_key],
                "start": clock,
                "revision": is_revision,
                "views_before": views,
                "review_at": None,
                "answers": [],
            }
            right, kc_right, kc_total = 0, {}, {}
            for entry in entries:
                kc_id, entry_id = str(entry["kc_id"]), str(entry["entry_id"])
                seconds = int(np.clip(rng.lognormal(np.log(25.0), 0.6), 3, 600))
                clock += seconds
                decay(kc_id, clock)
                logit = (
                    ability
                    + kc_offset[kc_id]
                    + gain[kc_id]
                    - kc_difficulty[kc_id]
                    - item_difficulty[entry_id]
                )
                p_right = GUESS_FLOOR + (1.0 - GUESS_FLOOR) / (
                    1.0 + np.exp(-1.2 * logit)
                )
                correct = int(rng.random() < p_right)
                partial = bool(rng.random() < 0.15)
                right += correct
                kc_right[kc_id] = kc_right.get(kc_id, 0) + correct
                kc_total[kc_id] = kc_total.get(kc_id, 0) + 1
                gain[kc_id] += learn_rate / (1.0 + 0.3 * practice[kc_id])
                practice[kc_id] += 1
                probabilities.append(float(p_right))
                outcomes.append(correct)
                attempt["answers"].append(
                    {
                        "entry_id": entry["entry_id"],
                        "kc_id": kc_id,
                        "correct": correct,
                        "partial": partial and not correct,
                        "time": clock,
                        "seconds": seconds,
                    }
                )
            clock += 5
            attempt["finish"] = clock
            learner["attempts"].append(attempt)
            needed = _pass_fraction(quiz, pass_fraction)
            passed = right / len(entries) >= needed
            if use_pages:
                if rng.random() < review_propensity:
                    clock += int(rng.integers(20, 300))
                    attempt["review_at"] = clock
                    counts["reviews"] += 1
                if not passed and rng.random() < revise_propensity:
                    weak = [
                        kc for kc in kc_total if kc_right[kc] / kc_total[kc] < needed
                    ]
                    revision = (step, weak)
            if step == progress and passed and progress < len(quizzes) - 1:
                progress += 1

    manifest = {
        "simulated": True,
        "warning": (
            "Simulated learners. Results describe this generator, not real "
            "learners, and must not be reported as validity evidence."
        ),
        "generator": "item-response model with practice gains and forgetting (not BKT)",
        "seed": seed,
        "start_unix": int(start_unix),
        "learners": len(plan),
        "learners_with_answers": sum(1 for learner in plan if learner["attempts"]),
        "quiz_attempts": sum(len(learner["attempts"]) for learner in plan),
        "answer_events": len(outcomes),
        "overall_accuracy": round(float(np.mean(outcomes)), 4) if outcomes else None,
        "ceiling_auc": ceiling_auc(probabilities, outcomes),
        "pass_fraction_default": pass_fraction,
        "page_behaviour": (
            {
                **counts,
                "lesson_gain": lesson_gain,
                "assumption": (
                    "Reading a KC lesson adds lesson_gain x learn_rate to that KC's "
                    "practice gain. This effect is a generator assumption."
                ),
            }
            if use_pages
            else None
        ),
    }
    return plan, manifest


def simulate_answers(
    catalog,
    question_map,
    topic_map,
    n_learners=300,
    seed=7,
    start_unix=DEFAULT_START_UNIX,
    inactive_share=0.05,
):
    """Offline mode: ``(roster, events, manifest)`` in the collector's schemas.

    Each topic acts as one quiz from which an attempt draws 5-10 questions.
    """
    topics = _topic_groups(catalog, question_map, topic_map)
    if not topics:
        raise ValueError("No KC has both a catalog row and mapped questions")
    dimension_of = dict(zip(catalog["kc_id"], catalog["kc_dimension"].str.lower()))
    link_of = {
        str(row.question_bank_entry_id): row
        for row in question_map.itertuples(index=False)
    }
    items_of = (
        question_map.groupby("kc_id")["question_bank_entry_id"].apply(list).to_dict()
    )
    quizzes = [
        {
            "quiz_id": index,
            "entries": [
                {"entry_id": str(item), "kc_id": kc}
                for kc in topic_kcs
                for item in items_of[kc]
            ],
        }
        for index, (_, topic_kcs) in enumerate(topics, start=1)
    ]
    plan, manifest = simulate_plan(
        quizzes,
        n_learners=n_learners,
        seed=seed,
        start_unix=start_unix,
        inactive_share=inactive_share,
        session_scale=6.0,
        sample_range=(5, 10),
    )

    roster, events = [], []
    quiz_attempt_id = question_attempt_id = 0
    for learner in plan:
        roster.append(
            {
                "learner_id": learner["learner_id"],
                "course_id": SIMULATED_COURSE_ID,
                "enrol_start_unix": learner["enrol_start"],
                "enrol_end_unix": 0,
            }
        )
        event_index = 0
        for attempt in learner["attempts"]:
            quiz_attempt_id += 1
            for answer in attempt["answers"]:
                question_attempt_id += 1
                event_index += 1
                link = link_of[str(answer["entry_id"])]
                events.append(
                    {
                        "learner_id": learner["learner_id"],
                        "event_index": event_index,
                        "item_id": f"moodle-qbe:{answer['entry_id']}",
                        "question_bank_entry_id": answer["entry_id"],
                        "kc_id": answer["kc_id"],
                        "kc_dimension": dimension_of.get(
                            answer["kc_id"], str(link.kc_dimension).lower()
                        ),
                        "event_type": "answer",
                        "timestamp": answer["time"],
                        "response_time_s": answer["seconds"],
                        "correct": answer["correct"],
                        # Partial credit is not full credit, as in the collector.
                        "raw_fraction": (
                            1.0
                            if answer["correct"]
                            else (0.5 if answer["partial"] else 0.0)
                        ),
                        "max_mark": 1.0,
                        "quiz_attempt_id": quiz_attempt_id,
                        "question_attempt_id": question_attempt_id,
                        "quiz_id": attempt["quiz_id"],
                        "attempt_number": attempt["attempt_number"],
                        "mapping_version": link.mapping_version,
                        "mapping_source": link.mapping_source,
                    }
                )
    return (
        pd.DataFrame(roster, columns=ROSTER_COLUMNS),
        pd.DataFrame(events, columns=ANSWER_EVENT_COLUMNS),
        manifest,
    )


def simulate(
    output_dir=DEFAULT_SIMULATED_DIR,
    course_dir=None,
    n_learners=300,
    seed=7,
    start_unix=DEFAULT_START_UNIX,
):
    """Write a complete simulated data directory and return its manifest."""
    output_dir = Path(output_dir)
    marker = output_dir / SIMULATION_MANIFEST_NAME
    if (output_dir / ANSWER_EVENTS_FILE).exists() and not marker.exists():
        raise ValueError(
            f"{output_dir} holds collector data without a simulation manifest; "
            "refusing to overwrite real learner data with simulated answers."
        )
    if course_dir is not None:
        if Path(course_dir).resolve() == output_dir.resolve():
            raise ValueError(
                "The simulator output directory must differ from the course directory"
            )
        catalog, question_map, topic_map = load_course(course_dir)
        course_source = str(course_dir)
    else:
        catalog, question_map, topic_map = make_course()
        course_source = "synthetic course (knowledge_engine.simulator.make_course)"
    roster, events, plan_manifest = simulate_answers(
        catalog,
        question_map,
        topic_map,
        n_learners=n_learners,
        seed=seed,
        start_unix=start_unix,
    )

    if output_dir.exists() and marker.exists():
        shutil.rmtree(output_dir)  # only ever a directory this simulator wrote
    output_dir.mkdir(parents=True, exist_ok=True)
    catalog.to_csv(output_dir / KC_CATALOG_FILE, index=False)
    question_map.to_csv(output_dir / QUESTION_KC_MAP_FILE, index=False)
    topic_map.to_csv(output_dir / KC_TOPIC_MAP_FILE, index=False)
    roster.to_csv(output_dir / ROSTER_FILE, index=False)
    events.to_csv(output_dir / ANSWER_EVENTS_FILE, index=False)
    manifest = {
        **plan_manifest,
        "course_source": course_source,
        "kcs": int(len(catalog)),
        "questions": int(len(question_map)),
    }
    write_json(marker, manifest)
    return manifest
